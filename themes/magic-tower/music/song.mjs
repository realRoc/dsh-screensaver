// 音名 → MIDI（C4 = 60）。写成 'D5'、'C#5'、'Bb4'。
const NOTE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 }
export function m(name) {
  const r = /^([A-G])(#|b)?(-?\d)$/.exec(name)
  if (!r) throw new Error(`bad note ${name}`)
  return 12 * (Number(r[3]) + 1) + NOTE[r[1]] + (r[2] === '#' ? 1 : r[2] === 'b' ? -1 : 0)
}

