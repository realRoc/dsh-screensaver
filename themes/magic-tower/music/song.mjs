// 《螺旋书阶》（Spiral Stair）—— 魔法书斋爬塔的 BGM。
// 这一个文件就是曲子本身：和弦、旋律、贝斯、鼓，全部按「第几小节第几拍」写。
// 改这里 → `node tools/tower-bgm/build.mjs` → 重新出 MIDI、音频和塔里的特效乐谱，三者永远对齐。
//
// ── 乐理设计 ─────────────────────────────────────────────────────────────
// 调式：D 多利亚（D E F G A B C）。比自然小调多一个还原 B（升高的第六级），
//       小调的神秘里带一点「还有希望」——夜里的书斋、骑士要往上爬。
// 速度：120 BPM，4/4。一拍 0.5 秒、一小节 2 秒，后期剪 MV 好算。
// 节奏性格：3+3+2（十六分音符 3、3、2 一组，也就是 tresillo）贯穿全曲——
//       主题动机、贝斯、副歌底鼓、间奏的三声重击都用它，所以听起来是「一首歌」不是一堆乐器。
// 主题动机：A–D–E–F（5 → 1 → 2 → 3），先跳四度再级进上行 = 迈上一级台阶再往上走。
// 叙事（调式随塔往上变）：
//   前奏  D 多利亚 + D 持续音        书斋里，书页翻开
//   A 段  i–IV（Dm–G，多利亚招牌）→ ♭VI–♭VII → V（A 大三，借和声小调的 C#）  进塔
//   B 段  贝斯一小节升一级 D E F G A B♭ C C#，旋律把动机逐级往上模进        爬螺旋楼梯
//   副歌  贝斯掉回低八度，安达卢西亚进行 i–♭VII–♭VI–V（Dm C B♭ A）          塔身全亮
//   间奏  全停，只剩钟琴独奏动机；三声 3+3+2 重击（「Boom!」）；鼓过门        所长sama 式的急停
//   终副歌 结尾变成 D 大三（皮卡第三度），动机 A–D–E–F 变成 A–D–E–F#        登顶，看见月亮
//   最后一小节只剩琶音，接回前奏的 Dm —— 从大调落回小调 = 回到书斋，无缝循环。
// ────────────────────────────────────────────────────────────────────────

export const BPM = 120
