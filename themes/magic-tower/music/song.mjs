//
// ── 乐理设计 ─────────────────────────────────────────────────────────────
// 性格：静谧、神秘、优雅，但进塔那一下要有第一波高潮。没有鼓组，高潮靠弦乐、合唱、竖琴刮奏和定音鼓。
// 拍子：3/4 慢圆舞曲，♩ = 72。一拍 0.833 秒、一小节 2.5 秒，34 小节 = 85 秒一个循环。
// 调性：D 小调。神秘感来自几种「不落地」的和弦颜色：
//       ♭VI maj7（B♭）—— 利底亚的亮，像月光照进来；♭II maj7#11（E♭）—— 那不勒斯和弦，拐角后面还有一层楼；
//       V7sus4（A 挂四）—— 属和弦悬着不解决，循环接回开头时是一口气接上的。
// 无限向上：钢片琴的「谢泼德琶音」贯穿全曲——每个音都是比上一个更高的下一个和弦音，同一个音同时在几个八度上响，
//       音量按音区取钟形曲线：最高那层淡出时最低那层淡入，听起来一直往上、永远到不了顶 —— 就是这座塔。
// 主题动机：D – A（五度跳上去）– 再一级一级落下来。抬头望一眼，再慢慢走。
// 叙事（视频里的画面在括号里）：
//   前奏  0–3   D 持续音上 Dm9 → B♭maj7/D：钢片琴和弦乐铺底（书房，骑士在读书）
//   蓄势  4–5   Gm9 → A7♭9，定音鼓滚奏渐强、竖琴刮奏一路往上（书页越翻越快，镜头扎进书里）
//   升腾  6–13  属七「骗」到 B♭maj7（阻碍终止）—— 门打开的那一下，全体奏响（光爆、俯冲进塔）；
//               低音一小节升一级 B♭ C D E♭ F G A A，弦乐把动机一级级往上推，第 10 小节到最高点：光之巨剑落下
//   A 段  14–21 回到安静：长笛唱主题，竖琴「一、二」两下托着
//   静息  22–25 D 持续音，只剩琶音和合唱：星井吸一口气（星辉脉冲）
//   A′段  26–33 主题回来，弦乐低八度陪着，第二把剑落在回来的第一拍；结尾停在 A 挂四上，接回前奏
//   尾声  34    （只在完整版里）落到 Dm(add9)，余音（一本书飞回来，回到书房）
// ────────────────────────────────────────────────────────────────────────

